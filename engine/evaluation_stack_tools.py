def _write(path: Path, value: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def _environment() -> tuple[Path, list[str]]:
    errors = []
    docker = shutil.which("docker")
    if docker:
        inspect = subprocess.run([docker, "image", "inspect", CONTAINER_ID, "--format", "{{.Id}}"], text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=False)
        if inspect.returncode or inspect.stdout.strip() != CONTAINER_ID:
            errors.append(f"pinned evaluation container is unavailable: {CONTAINER_ID}")
    else:
        errors.append("docker is unavailable")
    root = Path(os.environ.get("SOC_IMAGE_K230_TOOLCHAIN_ARCHIVES", "/root/.kendryte/k230_toolchains")).resolve()
    for name, digest in TOOLCHAINS.items():
        path = root / name
        if not path.is_file() or sha256(path) != digest:
            errors.append(f"toolchain archive is missing or has the wrong hash: {name}")
    return root, errors


def _run(command: list[str], log: Path) -> None:
    log.parent.mkdir(parents=True, exist_ok=True)
    with log.open("a", encoding="utf-8") as stream:
        stream.write("$ " + " ".join(command) + "\n")
        proc = subprocess.run(command, text=True, stdout=stream, stderr=subprocess.STDOUT, check=False)
    if proc.returncode:
        raise RuntimeError(f"evaluation command failed ({proc.returncode}); see {log}")


def _image_details(path: Path) -> dict[str, Any]:
    with path.open("rb") as stream:
        mbr = stream.read(512)
    partitions = [mbr[446 + index * 16 + 4] for index in range(4)] if len(mbr) == 512 else []
    return {
        "name": path.name, "sha256": sha256(path), "bytes": path.stat().st_size,
        "mbr_signature_pass": len(mbr) == 512 and mbr[510:512] == b"\x55\xaa",
        "partition_table_pass": sum(value != 0 for value in partitions) >= 2,
    }


def _payload_hashes(payload: Path) -> dict[str, str]:
    if payload.is_symlink() or not payload.is_dir():
        raise RuntimeError("evaluation payload must be a real directory")
    hashes = {}
    for path in sorted(payload.rglob("*")):
        relative = path.relative_to(payload).as_posix()
        if path.is_symlink():
            raise RuntimeError(f"evaluation payload contains a symlink: {relative}")
        if path.name == "__pycache__" or path.suffix.lower() in {".pyc", ".pyo", ".mpy"}:
            raise RuntimeError(f"evaluation payload contains generated bytecode: {relative}")
        if path.is_file():
            hashes[relative] = sha256(path)
    if not hashes:
        raise RuntimeError("evaluation payload is empty")
    return hashes


def _readback_payload(image: Path, payload: Path, hashes: dict[str, str], out: Path) -> tuple[bool, str]:
    analysis = k230_image_analyze.analyze(image, out / "analysis")
    partition = next((item for item in analysis["partitions"] if item["index"] == 2), None)
    if partition is None:
        return False, analysis["pre_partition_boot_region"]["sha256"]
    checks = []
    for relative in hashes:
        try:
            checks.append(product_image_verify._read(image, partition["offset_bytes"], relative) == (payload / relative).read_bytes())
        except RuntimeError:
            checks.append(False)
    return bool(checks) and all(checks), analysis["pre_partition_boot_region"]["sha256"]


def _verification(image: dict[str, Any]) -> dict[str, Any]:
    return {
        "schema": "soc-image.evaluation-verification.v1", "source_lock_pass": True,
        "container_lock_pass": True, "toolchain_lock_pass": True,
        "image_size_pass": image["bytes"] >= 512 * 1024 * 1024,
        "mbr_signature_pass": image["mbr_signature_pass"], "partition_table_pass": image["partition_table_pass"],
        "production_ancestry_excluded_pass": True,
    }


def _build_export(source: Path, archive_root: Path, artifacts: Path, log: Path, jobs: int) -> tuple[dict[str, Any], dict[str, Any]]:
    with tempfile.TemporaryDirectory(prefix="canmv-toolchains-") as temporary:
        toolchains = Path(temporary)
        for name in TOOLCHAINS:
            with tarfile.open(archive_root / name, mode="r:bz2") as archive:
                archive.extractall(toolchains, filter="data")
        _run([
            "docker", "run", "--rm", "--network", "none", "--hostname", "canmv-builder",
            "-v", f"{source}:{CONTAINER_WORKDIR}",
            "-v", f"{toolchains}:/home/runner/.kendryte/k230_toolchains:ro",
            "-w", CONTAINER_WORKDIR, CONTAINER_ID, "sh", "-lc",
            f"make {BOARD_CONFIG} && make -j{jobs} MICROPY_GIT_TAG=v1.8-0-gc2d1f5c MICROPY_GIT_HASH=c2d1f5c",
        ], log)
    images = [path for path in (source / "output" / BOARD_CONFIG).glob("*_nncase_*.img") if path.is_file() and path.stat().st_size >= 512 * 1024 * 1024]
    if len(images) != 1:
        raise RuntimeError(f"evaluation build produced {len(images)} full SD images")
    base = images[0]
    payload = ROOT / PAYLOAD
    payload_hashes = _payload_hashes(payload)
    with tempfile.TemporaryDirectory(prefix="canmv-compose-") as temporary:
        temporary_root = Path(temporary)
        temporary_out = temporary_root / "compose"
        composed = k230_image_compose.compose(base, temporary_out, payload=payload, install_main=False)
        if not composed.get("ok"):
            raise RuntimeError("source-built image composition failed")
        candidate = Path(composed["image"])
        readback = product_image_verify.verify(candidate, base, payload, ROOT / PRODUCT, temporary_root / "readback")
        if not readback.get("ok"):
            raise RuntimeError("source-built candidate payload readback failed")
        compose_report = json.loads((temporary_out / "k230_image_compose_report.json").read_text(encoding="utf-8"))
        base_sha256 = compose_report["manifest"]["base_image_sha256"]
        base_boot_sha256 = compose_report["analysis"]["pre_partition_boot_region"]["sha256"]
        final_boot_sha256 = compose_report["final_analysis"]["pre_partition_boot_region"]["sha256"]
        final_sha256 = compose_report["final_analysis"]["image_sha256"]
        if base_sha256 != sha256(base) or final_sha256 != sha256(candidate) or base_boot_sha256 != final_boot_sha256 or not readback["evidence"]["boot_region_preserved"]:
            raise RuntimeError("image composition hash evidence mismatch")
        destination = artifacts / IMAGE_ARTIFACT
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(candidate, destination)
    evidence = {
        "payload_sha256": payload_hashes,
        "source_built_base_sha256": base_sha256,
        "source_built_base_boot_region_sha256": base_boot_sha256,
        "final_sha256": final_sha256,
    }
    return _image_details(destination), evidence


def generate_canmv_evaluation_image(context: Any) -> dict[str, Any]:
    archive_root, errors = _environment()
    if errors:
        return {
            "status": "blocked", "outputs": [],
            "blocker": {"code": "evaluation_environment_missing", "reason": "; ".join(errors), "retryable": True, "owner": "SourceDiscoveryAgent"},
        }
    jobs_text = os.environ.get("SOC_IMAGE_BUILD_JOBS", "8")
    if not jobs_text.isdigit() or not 1 <= int(jobs_text) <= 64:
        raise RuntimeError("SOC_IMAGE_BUILD_JOBS must be an integer from 1 through 64")
    root = context.worktree / "generated/evaluation/canmv"
    log = context.artifact_dir / LOG_ARTIFACT
    with tempfile.TemporaryDirectory(prefix="canmv-evaluation-") as temporary:
        source = Path(temporary) / "source"
        stack = export_internal_evaluation_stack(context, STACK_ID, source)
        image, evidence = _build_export(source, archive_root, context.artifact_dir, log, int(jobs_text))
    report = _verification(image)
    manifest = {
        "schema": "soc-image.evaluation-build.v1", "generator": "SourceDiscoveryAgent",
        "task_id": context.task_id, "hardware_ir_sha256": context.hardware_ir_sha256,
        "classification": "local_test_candidate", "redistribution_allowed": False,
        "production_build_input_allowed": False,
        "gates": {"licensing_resolved": False, "physical_hil_resolved": False},
        "prohibited_uses": ["production_build_input", "release_product"],
        "stack": {"id": stack["id"], "source_lock_sha256": stack["source_lock_sha256"], "manifest_sha256": stack["manifest_sha256"], "repositories": len(stack["repositories"])},
        "container_id": CONTAINER_ID, "toolchains": TOOLCHAINS, "board_config": BOARD_CONFIG,
        "canmv_source_used": True, "image": image, **evidence,
    }
    _write(root / "manifest.json", manifest)
    _write(root / "verification.json", report)
    return {"status": "passed", "outputs": list(context.outputs), "artifacts": [IMAGE_ARTIFACT, LOG_ARTIFACT], "verification": report}


def verify_canmv_evaluation_image(context: Any) -> list[str]:
    errors = [f"missing evaluation output: {path}" for path in context.outputs if not (context.worktree / path).is_file()]
    image_path = context.artifact_dir / IMAGE_ARTIFACT
    log_path = context.artifact_dir / LOG_ARTIFACT
    if not image_path.is_file() or not log_path.is_file():
        return [*errors, "evaluation image or build log is missing"]
    root = context.worktree / "generated/evaluation/canmv"
    manifest = json.loads((root / "manifest.json").read_text(encoding="utf-8"))
    report = json.loads((root / "verification.json").read_text(encoding="utf-8"))
    lock_path, _, lock = _promoted_sources(context)
    stack = [item for item in lock["reference_stacks"] if item["id"] == STACK_ID and item["decision"] == "internal_evaluation"]
    details = _image_details(image_path)
    if manifest.get("task_id") != context.task_id or manifest.get("hardware_ir_sha256") != context.hardware_ir_sha256:
        errors.append("evaluation manifest is not task and Hardware IR bound")
    if (
        manifest.get("classification") != "local_test_candidate"
        or manifest.get("redistribution_allowed") is not False
        or manifest.get("production_build_input_allowed") is not False
        or manifest.get("gates") != {"licensing_resolved": False, "physical_hil_resolved": False}
    ):
        errors.append("evaluation artifact classification is unsafe")
    expected_stack = stack[0] if len(stack) == 1 else None
    manifest_stack = manifest.get("stack", {})
    if (
        expected_stack is None
        or manifest_stack.get("id") != STACK_ID
        or manifest_stack.get("source_lock_sha256") != sha256(lock_path)
        or manifest_stack.get("manifest_sha256") != expected_stack["manifest_sha256"]
        or manifest_stack.get("repositories") != len(expected_stack["repositories"])
    ):
        errors.append("evaluation artifact is not bound to the promoted internal stack")
    if manifest.get("container_id") != CONTAINER_ID or manifest.get("toolchains") != TOOLCHAINS:
        errors.append("evaluation environment lock mismatch")
    if manifest.get("image") != details:
        errors.append("evaluation image hash, size, or partition evidence mismatch")
    try:
        payload_hashes = _payload_hashes(ROOT / PAYLOAD)
        with tempfile.TemporaryDirectory(prefix="canmv-readback-") as temporary:
            readback_pass, boot_sha256 = _readback_payload(image_path, ROOT / PAYLOAD, payload_hashes, Path(temporary))
        if manifest.get("payload_sha256") != payload_hashes or not readback_pass:
            errors.append("evaluation payload hash or independent readback mismatch")
        if manifest.get("source_built_base_boot_region_sha256") != boot_sha256:
            errors.append("evaluation candidate did not preserve the source-built boot region")
    except (OSError, RuntimeError, ValueError, KeyError) as exc:
        errors.append(f"evaluation candidate readback failed: {exc}")
    base_sha256 = manifest.get("source_built_base_sha256")
    if manifest.get("final_sha256") != details["sha256"] or not isinstance(base_sha256, str) or len(base_sha256) != 64:
        errors.append("evaluation source-built or final image hash evidence mismatch")
    if report != _verification(details):
        errors.append("evaluation verification report is not deterministic")
    return errors


def selftest() -> None:
    with tempfile.TemporaryDirectory() as temporary:
        root = Path(temporary)
        image = root / "image.img"
        payload = bytearray(512)
        payload[446 + 4] = payload[462 + 4] = 0x0C
        payload[462 + 8:462 + 16] = (2).to_bytes(4, "little") + (1).to_bytes(4, "little")
        payload[510:512] = b"\x55\xaa"
        with image.open("wb") as stream:
            stream.write(payload)
        details = _image_details(image)
        assert details["mbr_signature_pass"] and details["partition_table_pass"]
        overlay = root / "overlay"
        overlay.mkdir()
        (overlay / "main.py").write_text("print('ok')\n", encoding="utf-8")
        hashes = _payload_hashes(overlay)
        assert list(hashes) == ["main.py"] and hashes["main.py"] == sha256(overlay / "main.py")
        original_read = product_image_verify._read
        try:
            product_image_verify._read = lambda *_args: (overlay / "main.py").read_bytes()
            assert _readback_payload(image, overlay, hashes, root / "readback") == (True, k230_image_analyze.digest(image, size=512))
        finally:
            product_image_verify._read = original_read
        for rejected in ("bad.pyc", "bad.pyo", "bad.mpy", "__pycache__"):
            path = overlay / rejected
            path.mkdir() if rejected == "__pycache__" else path.write_bytes(b"bad")
            try:
                _payload_hashes(overlay)
                raise AssertionError(f"accepted unsafe payload path: {rejected}")
            except RuntimeError:
                pass
            path.rmdir() if path.is_dir() else path.unlink()
        link = overlay / "main-link.py"
        link.symlink_to("main.py")
        try:
            _payload_hashes(overlay)
            raise AssertionError("accepted payload symlink")
        except RuntimeError:
            pass
        hardware_hash = "1" * 64
        worktree = root / "worktree"
        for index in range(7):
            _write(worktree / f"generated/component-{index}/manifest.json", {
                "hardware_ir_sha256": hardware_hash, "generator": "FixtureAgent", "task_id": f"task:{index}",
            })
        _write(worktree / "generated/evaluation/canmv/manifest.json", {
            "hardware_ir_sha256": "wrong", "canmv_source_used": True,
        })
        from engine.image_tools import _ancestry
        ancestry = _ancestry(type("Context", (), {"worktree": worktree, "hardware_ir_sha256": hardware_hash})())
        assert len(ancestry["manifests"]) == 7 and not ancestry["canmv_source_used"]


if __name__ == "__main__":
    selftest()
