def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base-image")
    parser.add_argument("--payload")
    parser.add_argument("--target", default=str(ROOT / "platforms/canaan_k230/target.json"))
    parser.add_argument("--package", help="optional generated .rvaic package to stage under sysu/rvaic/")
    parser.add_argument("--out", default=str(ROOT / "build/k230_project_image"))
    parser.add_argument("--data-partition-index", type=int, default=2)
    parser.add_argument("--no-main-launcher", action="store_true", help="do not install root main.py launcher")
    parser.add_argument("--no-inject", action="store_true")
    parser.add_argument("--selftest", action="store_true")
    args = parser.parse_args()
    if args.selftest:
        selftest()
        print("ok")
        return 0
    if not args.base_image:
        parser.error("--base-image is required unless --selftest is used")
    report = compose(
        Path(args.base_image).resolve(),
        Path(args.out).resolve(),
        Path(args.payload).resolve() if args.payload else None,
        target=Path(args.target).resolve() if args.target else None,
        package=Path(args.package).resolve() if args.package else None,
        install_main=not args.no_main_launcher,
        inject=not args.no_inject,
        data_partition_index=int(args.data_partition_index),
    )
    print(json.dumps(report, indent=2, sort_keys=True))
    return 0 if report["ok"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
