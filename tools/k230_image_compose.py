def utc_now() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def run(cmd: list[str]) -> subprocess.CompletedProcess[str]:
    env = os.environ.copy()
    env.setdefault("SOURCE_DATE_EPOCH", "946684800")
    return subprocess.run(cmd, env=env, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, check=False)


def write_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def load_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def copy_tree(src: Path, dst: Path) -> None:
    for item in src.rglob("*"):
        if not item.is_file():
            continue
        rel = item.relative_to(src)
        target = dst / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(item, target)


BOARD_PACKAGE_EXCLUDE_PREFIXES = (".acceptance/",)
BOARD_PACKAGE_EXCLUDE_NAMES = {"host_smoke", "host_compile.log", "host_run.log", "tvm_c_export.tar"}


def copy_board_package(src: Path, dst: Path) -> list[str]:
    copied = []
    for item in src.rglob("*"):
        if not item.is_file():
            continue
        rel = item.relative_to(src).as_posix()
        if rel.startswith(BOARD_PACKAGE_EXCLUDE_PREFIXES) or item.name in BOARD_PACKAGE_EXCLUDE_NAMES:
            continue
        target = dst / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(item, target)
        copied.append(rel)
    return sorted(copied)


def target_summary(target: Path | None) -> dict[str, Any]:
    if target is None:
        return {"present": False}
    data = load_json(target)
    return {
        "present": True,
        "path": str(target.resolve()),
        "target_hash": k230_image_analyze.digest(target),
        "name": data.get("name"),
        "isa": data.get("isa"),
        "abi": data.get("abi"),
        "cpu": data.get("cpu"),
        "board": data.get("board", {}),
        "boot": data.get("boot", {}),
        "rvv": data.get("rvv", {}),
        "npu": data.get("npu", {}),
    }


def payload_paths(root: Path) -> list[str]:
    return sorted(item.relative_to(root).as_posix() for item in root.rglob("*") if item.is_file())


