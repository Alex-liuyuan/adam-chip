def denoise_vectors() -> tuple[list[float], list[float]]:
    frame = [0.0, 0.125, -0.25, 0.5, -0.375, 0.25, 0.0, -0.125, 0.375, -0.5, 0.625, -0.25, 0.125, 0.0, -0.125, 0.25]
    expected = []
    for idx, value in enumerate(frame):
        left = frame[idx - 1] if idx > 0 else value
        right = frame[idx + 1] if idx + 1 < len(frame) else value
        expected.append(round(0.25 * left + 0.5 * value + 0.25 * right, 6))
    return frame, expected


