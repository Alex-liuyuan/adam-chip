def inject_payload(image: Path, partition: dict[str, Any], payload: Path, mount_root: Path) -> dict[str, Any]:
    del mount_root
    image_spec = f"{image}@@{partition['offset_bytes']}"
    outputs = []
    for item in sorted(payload.iterdir()):
        proc = run(["mcopy", "-m", "-i", image_spec, "-s", "-o", str(item), "::/"])
        outputs.append(proc.stdout.strip())
        if proc.returncode != 0:
            return {"ok": False, "error": proc.stdout.strip(), "item": str(item)}
    return {"ok": True, "partition_index": partition["index"], "payload": str(payload), "files": payload_paths(payload), "tool": "mcopy", "output": outputs}


def compose(
    base_image: Path,
    out: Path,
    payload: Path | None = None,
    *,
    target: Path | None = None,
    package: Path | None = None,
    install_main: bool = True,
    inject: bool = True,
    data_partition_index: int = 2,
) -> dict[str, Any]:
    out.mkdir(parents=True, exist_ok=True)
    image = out / "SYSUOS_K230_V3P0.img"
    shutil.copyfile(base_image, image)
    analysis = k230_image_analyze.analyze(image, out / "analysis")
    manifest = {
        "producer": "sysu-soc-image-factory",
        "artifact_kind": "k230_derived_sdcard_image",
        "generated_at": utc_now(),
        "base_image": str(base_image.resolve()),
        "base_image_sha256": k230_image_analyze.digest(base_image),
        "image": str(image),
        "target": target_summary(target),
        "derived_from_verified_base_image": True,
        "self_hosted_boot_chain": False,
        "boot_chain_source": "verified_official_base_image_raw_boot_region",
        "not_claimed": [
            "The raw K230 boot region is preserved from the base image.",
            "This is a bootable integration image, not a from-source SYSU system image.",
            "Board execution is not claimed until serial markers are captured from the physical board.",
        ],
    }
    generated_payload = payload is None
    payload_dir = payload.resolve() if payload else default_payload(out, manifest, package=package, install_main=install_main)
    manifest["payload_files"] = payload_paths(payload_dir)
    payload_host_smoke = run_payload_host_smoke(payload_dir, package_expected=package is not None) if install_main else {"ok": False, "skipped": True, "reason": "main launcher disabled"}
    partition = next((p for p in analysis["partitions"] if p["index"] == data_partition_index), None)
    injection = {"ok": False, "skipped": True, "reason": "payload injection disabled"}
    if inject:
        if not partition:
            injection = {"ok": False, "error": f"partition {data_partition_index} was not found"}
        else:
            injection = inject_payload(image, partition, payload_dir, out / "mnt")
    final_analysis = k230_image_analyze.analyze(image, out / "analysis_final")
    boot_before = analysis["pre_partition_boot_region"]["sha256"]
    boot_after = final_analysis["pre_partition_boot_region"]["sha256"]
    boot_region_preserved = boot_before == boot_after
    manifest.update(
        {
            "payload_dir": str(payload_dir),
            "payload_injection": injection,
            "boot_region_preserved": boot_region_preserved,
            "pre_partition_boot_region_sha256": boot_after,
            "image_sha256": k230_image_analyze.digest(image),
            "image_md5": k230_image_analyze.digest(image, "md5"),
        }
    )
    injected_files = set(injection.get("files", [])) if isinstance(injection.get("files"), list) else set()
    phase2_evidence = {
        "official_layout_analysis_pass": bool(analysis.get("ok")),
        "boot_region_preserved": boot_region_preserved,
        "payload_injection_pass": bool(not inject or injection.get("ok")),
        "root_main_present": (not install_main) or "main.py" in injected_files or not inject,
        "sysu_run_all_present": (not generated_payload) or "sysu/run_all.py" in injected_files or not inject,
        "sysu_manifest_present": (not generated_payload) or "sysu/image_manifest.json" in injected_files or not inject,
        "self_hosted_boot_chain_false": manifest["self_hosted_boot_chain"] is False,
        "payload_host_smoke_pass": (not install_main) or bool(payload_host_smoke.get("ok")),
    }
    if package is not None:
        phase2_evidence["rvaic_package_probe_host_pass"] = bool(payload_host_smoke.get("ok"))
    ok = all(phase2_evidence.values())
    write_json(
        out / "k230_image_compose_report.json",
        {
            "ok": ok,
            "phase2_evidence": phase2_evidence,
            "payload_host_smoke": payload_host_smoke,
            "manifest": manifest,
            "analysis": analysis,
            "final_analysis": final_analysis,
        },
    )
    write_json(image.with_suffix(image.suffix + ".manifest.json"), manifest)
    return {"ok": ok, "image": str(image), "manifest": str(image.with_suffix(image.suffix + ".manifest.json")), "injection": injection}


def selftest() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        base = root / "base.img"
        data = bytearray(k230_image_analyze.SECTOR * 20)
        data[510:512] = b"\x55\xaa"
        entry = bytearray(16)
        entry[4] = 0x0C
        entry[8:12] = (4).to_bytes(4, "little")
        entry[12:16] = (8).to_bytes(4, "little")
        data[446:462] = entry
        base.write_bytes(data)
        report = compose(base, root / "out", inject=False)
        assert report["ok"], report
        manifest = json.loads(Path(report["manifest"]).read_text(encoding="utf-8"))
        assert manifest["self_hosted_boot_chain"] is False
        assert manifest["payload_entrypoints"]["audio_denoise_smoke"] == "sysu/audio_denoise_smoke.py"
        assert manifest["boot_region_preserved"] is True
        assert Path(report["image"]).exists()
        payload = root / "out" / "payload"
        assert (payload / "sysu" / "run_all.py").exists()
        assert "SYSU_K230_AUDIO_DENOISE_DIFF_PASS" in (payload / "sysu" / "audio_denoise_smoke.py").read_text(encoding="utf-8")
        assert json.loads((root / "out" / "k230_image_compose_report.json").read_text(encoding="utf-8"))["phase2_evidence"]["self_hosted_boot_chain_false"]
        target = root / "target.json"
        write_json(target, {"name": "test-k230", "isa": "rv64gcv", "abi": "lp64d"})
        package = root / "audio_fir_denoiser.rvaic"
        (package / "contracts").mkdir(parents=True)
        (package / "evidence").mkdir()
        (package / ".acceptance").mkdir()
        write_json(package / "contracts" / "target_contract.json", {"target_hash": k230_image_analyze.digest(target)})
        write_json(package / "evidence" / "proof_manifest.json", {"ok": True})
        (package / ".acceptance" / "host_run.log").write_text("host only\n", encoding="utf-8")
        packaged = compose(base, root / "with_package", target=target, package=package, inject=False)
        assert packaged["ok"], packaged
        packaged_report = json.loads((root / "with_package" / "k230_image_compose_report.json").read_text(encoding="utf-8"))
        markers = packaged_report["payload_host_smoke"]["markers"]
        assert markers["SYSU_K230_RVAIC_PACKAGE_PRESENT"], markers
